#!/usr/bin/env python3
"""Render deterministic CSV/HTML views from a kit markdown artifact.

The markdown artifact is canonical; the exports are derived, never
hand-edited. Rendering deterministically eliminates the CSV-vs-markdown
drift class entirely and guarantees the script-free, single-file HTML the
flow examples require.

- ``csv`` extracts the kind's primary table with a per-kind column mapping
  (register → ``candidate,relationship,why_in_scope,evidence,next_action``,
  matching the flow-02 fixture header; evidence cells joined with ``; ``).
- ``html`` renders the whole artifact as one dependency-free page using the
  flow examples' style constants, with a footer pointing at the evidence
  index. Only the markdown subset the kit templates use is supported:
  headings, paragraphs, bullet lists, pipe tables, ``code``, **bold**.

Exit codes: 0 = written, 1 = usage error or unsupported kind/format.

Usage:
    python3 render_views.py <artifact.md> --format csv,html [--out-dir DIR]
"""

from __future__ import annotations

import argparse
import csv
import html
import io
import re
import sys
from pathlib import Path

ID_LINE_RE = re.compile(r"\*\*ID\*\*:\s*`(cpt-[a-z0-9-]+)`")
HEADING_RE = re.compile(r"^(#{1,6})\s+(.*)$")
TOC_MARKER_RE = re.compile(r"<!--\s*/?toc(stop)?\s*-->|<!--\s*generated by.*?-->", re.IGNORECASE)

STYLE = (
    "body{font:16px/1.45 system-ui,sans-serif;color:#172033;max-width:1200px;"
    "margin:40px auto;padding:0 24px}"
    "h1{margin-bottom:4px}h2{margin-top:32px}"
    ".note{color:#526070}"
    "table{border-collapse:collapse;width:100%;margin-top:16px}"
    "th,td{border:1px solid #d6dce5;padding:12px;text-align:left;vertical-align:top}"
    "th{background:#172033;color:#fff}"
    "tbody tr:nth-child(even){background:#f6f8fb}"
    "code{background:#f6f8fb;border:1px solid #d6dce5;border-radius:4px;"
    "padding:1px 5px;font-size:14px}"
    ".callout{background:#eef2ff;border-left:4px solid #4f46e5;padding:12px 16px;"
    "margin-top:16px}"
    ".boundary{background:#fff7ed;border-left:4px solid #ea580c;padding:12px 16px;"
    "margin-top:16px}"
)
NEGATIVE_HEADING_RE = re.compile(r"boundary|unknown|unestablished|limit", re.IGNORECASE)
HYPOTHESIS_HEADING_RE = re.compile(r"borrow|hypothesis", re.IGNORECASE)

# kind -> (section name, [(source column header, csv field)])
CSV_MAPS: dict[str, tuple[str, list[tuple[str, str]]]] = {
    "reg": ("Candidates", [
        ("Candidate", "candidate"),
        ("Classification", "relationship"),
        ("Why it is in scope", "why_in_scope"),
        ("Evidence", "evidence"),
        ("Next action", "next_action"),
    ]),
    "wat": ("Watch Register", [
        ("Watched field", "watched_field"),
        ("Observation", "observation"),
        ("Evidence", "evidence"),
        ("Next comparison rule", "next_comparison_rule"),
    ]),
    "tax": ("Feature Rows", [
        ("Feature / scenario", "feature"),
        ("Definition", "definition"),
        ("Inclusion criteria", "inclusion_criteria"),
        ("Evidence", "evidence"),
    ]),
    "rev": ("Run Coverage", [
        ("Lead", "lead"),
        ("Next action", "next_action"),
        ("Status", "status"),
        ("Fulfilled by", "fulfilled_by"),
        ("Follow-up", "follow_up"),
    ]),
    "mech": ("Mechanism Map", [
        ("Mechanism", "mechanism"),
        ("Observed example", "observed_example"),
        ("Direct input", "direct_input"),
        ("Documented action", "documented_action"),
        ("What is not established", "not_established"),
        ("Evidence", "evidence"),
    ]),
    "oss": ("Repository Review", [
        ("Repository", "repository"),
        ("Component scope", "component_scope"),
        ("Licence and activity", "licence_and_activity"),
        ("Deployability", "deployability"),
        ("Reuse relevance and follow-up", "reuse_relevance"),
        ("Evidence", "evidence"),
    ]),
    "cmp": ("Matrix", [
        ("Company / product", "company"),
        ("Feature / mechanism", "feature_mechanism"),
        ("Status", "status"),
        ("Availability", "availability"),
        ("Observed on", "observed_on"),
        ("Documented boundary", "documented_boundary"),
        ("Evidence", "evidence"),
    ]),
}


# The kit's ID kinds, for kind detection that survives hyphenated
# {system} slugs (`cpt-my-long-system-reg-slug`): scan the ID's segments
# left to right for the first known kind token instead of assuming a
# fixed position.
KNOWN_KINDS = {"req", "reg", "ori", "prof", "bor", "dos", "cmp", "oss",
               "mech", "wat", "rev", "tax"}


DIR_KINDS = {
    "RESEARCH-REQUEST": "req", "CANDIDATE-REGISTER": "reg",
    "ORIENTATION-CARD": "ori", "COMPANY-PROFILE": "prof",
    "COMPANY-DOSSIER": "dos", "COMPARISON-MATRIX": "cmp",
    "OSS-REVIEW": "oss", "MECHANISM-STUDY": "mech",
    "WATCH-REPORT": "wat", "RESEARCH-REVIEW": "rev",
    "FEATURE-TAXONOMY": "tax",
}


def kind_from_path(path: Path) -> str:
    """KIND-named ancestor directory beats ID-token scanning: a hyphenated
    {system} slug may itself contain a reserved kind token, and the
    project/kit layouts always shelve artifacts under their KIND dir."""
    for part in reversed(path.resolve().parts[:-1]):
        if part in DIR_KINDS:
            return DIR_KINDS[part]
    return ""


def artifact_kind(text: str) -> str:
    m = ID_LINE_RE.search(text)
    if not m:
        return ""
    for part in m.group(1).split("-")[1:-1]:
        if part in KNOWN_KINDS:
            return part
    return ""


def split_sections(text: str) -> list[tuple[int, str, str]]:
    sections: list[tuple[int, str, str]] = []
    level, current, buf = 0, "", []
    for line in text.splitlines():
        m = HEADING_RE.match(line)
        if m:
            sections.append((level, current, "\n".join(buf)))
            level, current, buf = len(m.group(1)), m.group(2).strip(), []
        else:
            buf.append(line)
    sections.append((level, current, "\n".join(buf)))
    return sections


def parse_table(body: str) -> tuple[list[str], list[list[str]]]:
    header: list[str] = []
    rows: list[list[str]] = []
    state = "before"
    for line in body.splitlines():
        if line.lstrip().startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if state == "before":
                header, state = cells, "rule"
            elif state == "rule":
                state = "rows"
            else:
                rows.append(cells)
        elif state == "rows":
            break
    return header, rows


def strip_inline(text: str) -> str:
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"\*\*([^*]*)\*\*", r"\1", text)
    return text.strip()


def render_csv(text: str, kind: str) -> str | None:
    mapping = CSV_MAPS.get(kind)
    if mapping is None:
        return None
    section_name, columns = mapping
    for level, heading, body in split_sections(text):
        # Only section headings qualify (the H1 title may contain the same
        # word, e.g. "Comparison Matrix — …" vs the "Matrix" section).
        if level < 2 or section_name.lower() not in heading.lower():
            continue
        header, rows = parse_table(body)
        if not header:
            continue
        indices: list[int | None] = []
        for source_col, _ in columns:
            idx = next((i for i, h in enumerate(header)
                        if strip_inline(h).lower() == source_col.lower()), None)
            indices.append(idx)
        buf = io.StringIO()
        writer = csv.writer(buf, lineterminator="\n")
        writer.writerow([field for _, field in columns])
        for row in rows:
            out = []
            for idx, (_, field) in zip(indices, columns):
                cell = strip_inline(row[idx]) if idx is not None and idx < len(row) else ""
                if field == "evidence":
                    cell = "; ".join(re.split(r"\s*[;,]\s*", cell))
                out.append(cell)
            writer.writerow(out)
        return buf.getvalue()
    return None


def inline_html(text: str) -> str:
    out = html.escape(text)
    out = re.sub(r"`([^`]*)`", r"<code>\1</code>", out)
    out = re.sub(r"\*\*([^*]*)\*\*", r"<strong>\1</strong>", out)
    return out


def body_html(body: str, css_class: str | None) -> list[str]:
    parts: list[str] = []
    lines = [l for l in body.splitlines()]
    i = 0
    open_wrap = False
    if css_class:
        parts.append(f'<div class="{css_class}">')
        open_wrap = True
    while i < len(lines):
        line = lines[i]
        if TOC_MARKER_RE.search(line) or line.strip().startswith("<!--"):
            # Drop comment blocks entirely (single- or multi-line).
            while i < len(lines) and "-->" not in lines[i]:
                i += 1
            i += 1
            continue
        if line.lstrip().startswith("|"):
            header, rows = parse_table("\n".join(lines[i:]))
            table_lines = 2 + len(rows)
            parts.append("<table><thead><tr>"
                         + "".join(f"<th>{inline_html(strip_inline(h))}</th>" for h in header)
                         + "</tr></thead><tbody>")
            for row in rows:
                parts.append("<tr>" + "".join(f"<td>{inline_html(c)}</td>" for c in row) + "</tr>")
            parts.append("</tbody></table>")
            i += table_lines
            continue
        if line.lstrip().startswith("- "):
            parts.append("<ul>")
            while i < len(lines) and lines[i].lstrip().startswith("- "):
                item = lines[i].lstrip()[2:]
                while i + 1 < len(lines) and lines[i + 1].startswith("  ") \
                        and not lines[i + 1].lstrip().startswith("- "):
                    i += 1
                    item += " " + lines[i].strip()
                parts.append(f"<li>{inline_html(item)}</li>")
                i += 1
            parts.append("</ul>")
            continue
        if line.strip():
            para = [line.strip()]
            while i + 1 < len(lines) and lines[i + 1].strip() \
                    and not lines[i + 1].lstrip().startswith(("|", "- ", "#", "<!--")):
                i += 1
                para.append(lines[i].strip())
            parts.append(f"<p>{inline_html(' '.join(para))}</p>")
        i += 1
    if open_wrap:
        parts.append("</div>")
    return parts


def render_html(text: str) -> str:
    sections = split_sections(text)
    title = "Artifact"
    parts: list[str] = []
    for level, heading, body in sections:
        if level == 1:
            title = strip_inline(heading)
        if level == 0 and not heading:
            parts.extend(body_html(body, None))
            continue
        if "table of contents" in heading.lower():
            continue
        css_class = None
        if level >= 2 and NEGATIVE_HEADING_RE.search(heading):
            css_class = "boundary"
        elif level >= 2 and HYPOTHESIS_HEADING_RE.search(heading):
            css_class = "callout"
        parts.append(f"<h{level}>{inline_html(strip_inline(heading))}</h{level}>")
        parts.extend(body_html(body, css_class))
    return (
        "<!doctype html>\n<html lang=\"en\">\n<meta charset=\"utf-8\">\n"
        f"<title>{html.escape(title)}</title>\n<style>{STYLE}</style>\n"
        + "\n".join(parts)
        + "\n<p class=\"note\">Evidence locators resolve in "
          "<code>competitive/evidence/index.tsv</code>.</p>\n</html>\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("artifact", type=Path)
    parser.add_argument("--format", required=True,
                        help="comma-separated: csv, html")
    parser.add_argument("--out-dir", type=Path, default=None,
                        help="default: <artifact-dir>/exports/")
    args = parser.parse_args()

    if not args.artifact.is_file():
        print(f"error: not a file: {args.artifact}", file=sys.stderr)
        return 1
    formats = [f.strip() for f in args.format.split(",") if f.strip()]
    unknown = [f for f in formats if f not in {"csv", "html"}]
    if unknown:
        print(f"error: unsupported format(s): {', '.join(unknown)}", file=sys.stderr)
        return 1

    text = args.artifact.read_text(encoding="utf-8")
    kind = kind_from_path(args.artifact) or artifact_kind(text)
    out_dir = args.out_dir or (args.artifact.parent / "exports")
    out_dir.mkdir(parents=True, exist_ok=True)

    for fmt in formats:
        if fmt == "csv":
            rendered = render_csv(text, kind)
            if rendered is None:
                print(f"error: no CSV view is defined for kind {kind!r}", file=sys.stderr)
                return 1
        else:
            rendered = render_html(text)
        out_path = out_dir / f"{args.artifact.stem}.{fmt}"
        out_path.write_text(rendered, encoding="utf-8")
        print(f"wrote {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
